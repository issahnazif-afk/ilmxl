// Shape is defined in FORMAT.md. Helpers below only build plain objects of that shape.

// Items with 3+ choices are rotated by a fixed amount derived from the question text,
// so the right answer is not always in the same position (deterministic across builds).
const mc = (q, choices, a, why) => {
  if (choices.length < 3) return { q, choices, a, why };
  let h = 0;
  for (const ch of q) h = (h * 31 + ch.codePointAt(0)) >>> 0;
  const r = h % choices.length;
  const rotated = choices.map((_, i) => choices[(i + r) % choices.length]);
  return { q, choices: rotated, a: (a - r + choices.length) % choices.length, why };
};
const t = (q, answer, accept, why) => ({ q, answer, accept, why });
const s = (say, board) => ({ say, board });

